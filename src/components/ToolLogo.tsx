export default function ToolLogo({ slug, fallback = "🔗", size = 48, className = "" }: Props) {
  const icon = BRAND_ICONS[slug];

  if (!icon) {
    // Emoji fallback
    return (
      <div
        className={className}
        style={{
          width: size, height: size,
          display: "grid", placeItems: "center",
          fontSize: size * 0.55, borderRadius: 10,
          background: "#f4f4f5",
        }}
        aria-hidden="true"
      >
        {fallback}
      </div>
    );
  }

  // Determine background: use a very light tint of the brand color
  const r = parseInt(icon.hex.slice(0, 2), 16);
  const g = parseInt(icon.hex.slice(2, 4), 16);
  const b = parseInt(icon.hex.slice(4, 6), 16);
  // If the color is very dark (e.g. #000000, #181717), use a neutral bg
  const luminance = 0.299 * r + 0.587 * g + 0.114 * b;
  const bgAlpha = luminance < 30 ? "0.08" : "0.12";
  const bgColor = `rgba(${r},${g},${b},${bgAlpha})`;
  // Icon color: use brand color, but if very dark lighten it
  const iconColor = luminance < 30 ? `#${icon.hex}` : `#${icon.hex}`;

  return (
    <div
      className={className}
      style={{
        width: size, height: size,
        display: "grid", placeItems: "center",
        borderRadius: size * 0.2,
        background: bgColor,
        flexShrink: 0,
      }}
      aria-hidden="true"
    >
      <svg
        viewBox="0 0 24 24"
        width={size * 0.58}
        height={size * 0.58}
        fill={iconColor}
        xmlns="http://www.w3.org/2000/svg"
        aria-hidden="true"
      >
        <path d={icon.path} />
      </svg>
    </div>
  );
}
